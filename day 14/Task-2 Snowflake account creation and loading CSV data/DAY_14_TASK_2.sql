CREATE DATABASE IF NOT EXISTS DB_AJI;

SHOW DATABASES LIKE 'DB_AJI';

CREATE SCHEMA IF NOT EXISTS SCHEMA_AJI;

USE SCHEMA DB_AJI.SCHEMA_AJI;

SHOW SCHEMAS IN DATABASE DB_AJI;

CREATE WAREHOUSE IF NOT EXISTS WAREHOUSE_AJI
   WAREHOUSE_SIZE = 'SMALL'
   AUTO_SUSPEND = 60
   AUTO_RESUME = TRUE
   INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE WAREHOUSE_AJI;

SHOW WAREHOUSES LIKE 'WAREHOUSE_AJI';

CREATE TABLE IF NOT EXISTS ORDERS(
    ORDER_ID VARCHAR(16),
    ORDER_DATETIME TIMESTAMP,
    CUSTOMER_ID VARCHAR(16),
    CITY VARCHAR(32),
    PRODUCT_NAME VARCHAR(64),
    CATEGORY VARCHAR(64),
    COST_PER_UNIT NUMBER(12,2),
    QUANTITY NUMBER(6,0),
    PAYMENT_METHOD VARCHAR(16),
    REVENUE NUMBER(12,2)
);

SHOW TABLES LIKE 'ORDERS' IN SCHEMA DB_AJI.SCHEMA_AJI;

DESCRIBE TABLE DB_AJI.SCHEMA_AJI.ORDERS;

CREATE FILE FORMAT IF NOT EXISTS AJI_CSV
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY =  '"'
    EMPTY_FIELD_AS_NULL = TRUE;

SHOW FILE FORMATS IN SCHEMA DB_AJI.SCHEMA_AJI;

CREATE STAGE IF NOT EXISTS AJI_STAGE FILE_FORMAT = AJI_CSV;

SHOW STAGES IN SCHEMA DB_AJI.SCHEMA_AJI;

LIST @DB_AJI.SCHEMA_AJI.AJI_STAGE;

COPY INTO DB_AJI.SCHEMA_AJI.ORDERS
FROM @DB_AJI.SCHEMA_AJI.AJI_STAGE
FILE_FORMAT = (FORMAT_NAME = 'DB_AJI.SCHEMA_AJI.AJI_CSV')
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_ORDERS FROM DB_AJI.SCHEMA_AJI.ORDERS;

SELECT CATEGORY, COUNT(*) AS ORDERS_COUNT
FROM ORDERS
GROUP BY CATEGORY
ORDER BY ORDERS_COUNT DESC;

SELECT * FROM ORDERS WHERE REVENUE > (SELECT AVG(REVENUE) FROM ORDERS);

DROP DATABASE IF EXISTS DB_AJI;

DROP WAREHOUSE IF EXISTS WAREHOUSE_AJI;