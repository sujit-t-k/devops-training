CREATE DATABASE IF NOT EXISTS AJI_FINANCE_DB;

SHOW DATABASES LIKE 'AJI_FINANCE_DB'; 

CREATE SCHEMA IF NOT EXISTS AJI_FINANCE_DB.AJI_FINANCE_SCHEMA;

USE SCHEMA AJI_FINANCE_DB.AJI_FINANCE_SCHEMA;

SHOW SCHEMAS IN DATABASE AJI_FINANCE_DB;

CREATE WAREHOUSE IF NOT EXISTS AJI_FINANCE_WH
    WAREHOUSE_SIZE = 'SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE AJI_FINANCE_WH;

SHOW WAREHOUSES LIKE 'AJI_FINANCE_WH';

CREATE TABLE IF NOT EXISTS AJI_FINANCE_DB.AJI_FINANCE_SCHEMA.AJI_FINANCE_TRANSACTIONS (
    TRANSACTION_ID         VARCHAR(32),
    TRANSACTION_TIMESTAMP  TIMESTAMP_NTZ,
    SENDER_ID              VARCHAR(32),
    RECEIVER_ID            VARCHAR(32),
    TRANSACTION_TYPE       VARCHAR(32),
    TRANSACTION_STATUS     VARCHAR(32),
    AMOUNT                 NUMBER(12,2),
    FEE_AMOUNT             NUMBER(10,2),
    PAYMENT_CATEGORY       VARCHAR(64),
    DEVICE_TYPE            VARCHAR(32),
    BANK_PARTNER           VARCHAR(64),
    LOCATION_CITY          VARCHAR(64)
);

SHOW TABLES LIKE 'AJI_FINANCE_TRANSACTIONS' IN SCHEMA AJI_FINANCE_DB.AJI_FINANCE_SCHEMA;

DESCRIBE TABLE AJI_FINANCE_DB.AJI_FINANCE_SCHEMA.AJI_FINANCE_TRANSACTIONS;

CREATE FILE FORMAT IF NOT EXISTS AJI_FINANCE_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    TIMESTAMP_FORMAT = 'YYYY-MM-DD HH24:MI:SS';

SHOW FILE FORMATS IN SCHEMA AJI_FINANCE_DB.AJI_FINANCE_SCHEMA;

CREATE STAGE IF NOT EXISTS AJI_FINANCE_STAGE
    FILE_FORMAT = AJI_FINANCE_CSV_FORMAT;

SHOW STAGES IN SCHEMA AJI_FINANCE_DB.AJI_FINANCE_SCHEMA;

LIST @AJI_FINANCE_DB.AJI_FINANCE_SCHEMA.AJI_FINANCE_STAGE;

COPY INTO AJI_FINANCE_DB.AJI_FINANCE_SCHEMA.AJI_FINANCE_TRANSACTIONS
FROM @AJI_FINANCE_DB.AJI_FINANCE_SCHEMA.AJI_FINANCE_STAGE
FILE_FORMAT = (FORMAT_NAME = 'AJI_FINANCE_DB.AJI_FINANCE_SCHEMA.AJI_FINANCE_CSV_FORMAT')
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_TRANSACTIONS 
FROM AJI_FINANCE_DB.AJI_FINANCE_SCHEMA.AJI_FINANCE_TRANSACTIONS;

SELECT 
    TRANSACTION_TYPE,
    COUNT(*) AS TXN_COUNT,
    SUM(AMOUNT) AS TOTAL_AMOUNT,
    ROUND(AVG(AMOUNT), 2) AS AVG_AMOUNT
FROM AJI_FINANCE_TRANSACTIONS
GROUP BY TRANSACTION_TYPE
ORDER BY TOTAL_AMOUNT DESC;

SELECT 
    LOCATION_CITY,
    TRANSACTION_STATUS,
    COUNT(*) AS STATUS_COUNT,
    SUM(AMOUNT) AS TOTAL_VOLUME
FROM AJI_FINANCE_TRANSACTIONS
GROUP BY LOCATION_CITY, TRANSACTION_STATUS
ORDER BY LOCATION_CITY, STATUS_COUNT DESC;

SELECT * 
FROM AJI_FINANCE_TRANSACTIONS 
WHERE TRANSACTION_STATUS = 'Success' 
  AND AMOUNT > (
      SELECT AVG(AMOUNT) 
      FROM AJI_FINANCE_TRANSACTIONS 
      WHERE TRANSACTION_STATUS = 'Success'
  )
ORDER BY AMOUNT DESC;

DROP DATABASE IF EXISTS AJI_FINANCE_DB;
DROP WAREHOUSE IF EXISTS AJI_FINANCE_WH;