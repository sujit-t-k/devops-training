CREATE DATABASE IF NOT EXISTS AJI_DB_V2;
CREATE SCHEMA IF NOT EXISTS AJI_DB_V2.AJI_SCHEMA_V2;

USE SCHEMA AJI_DB_V2.AJI_SCHEMA_V2;

CREATE WAREHOUSE IF NOT EXISTS AJI_WAREHOUSE_V2
    WAREHOUSE_SIZE = 'SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE AJI_WAREHOUSE_V2;

CREATE OR REPLACE TABLE CUSTOMERS (
    CUSTOMER_ID   VARCHAR(16),
    CUSTOMER_NAME VARCHAR(64),
    CITY          VARCHAR(32),
    SIGNUP_DATE VARCHAR(32),
    CUSTOMER_TIER VARCHAR(16)
);

CREATE OR REPLACE TABLE PRODUCTS (
    PRODUCT_ID       VARCHAR(16),
    PRODUCT_NAME     VARCHAR(64),
    PRODUCT_CATEGORY VARCHAR(32),
    UNIT_PRICE       NUMBER(10,2),
    STOCK_QUANTITY   INT
);

CREATE OR REPLACE TABLE ORDERS (
    ORDER_ID       VARCHAR(16),
    CUSTOMER_ID    VARCHAR(16),
    PRODUCT_ID     VARCHAR(16),
    QUANTITY       INT,
    ORDER_DATETIME TIMESTAMP_NTZ,
    ORDER_STATUS   VARCHAR(16),
    PAYMENT_MODE   VARCHAR(16)
);

CREATE OR REPLACE FILE FORMAT AJI_FILE_FORMAT_V2
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE AJI_STAGE_V2
    FILE_FORMAT = AJI_FILE_FORMAT_V2;

SHOW STAGES IN SCHEMA AJI_DB_V2.AJI_SCHEMA_V2;

SHOW FILE FORMATS IN AJI_DB_V2.AJI_SCHEMA_V2;

LIST @AJI_STAGE_V2;


COPY INTO CUSTOMERS
FROM @AJI_STAGE_V2
FILES = ('customers.csv')
FILE_FORMAT = (FORMAT_NAME = 'AJI_FILE_FORMAT_V2')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO PRODUCTS
FROM @AJI_STAGE_V2
FILES = ('products.csv')
FILE_FORMAT = (FORMAT_NAME = 'AJI_FILE_FORMAT_V2')
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ORDERS
FROM @AJI_STAGE_V2
FILES = ('orders.csv')
FILE_FORMAT = (FORMAT_NAME = 'AJI_FILE_FORMAT_V2')
ON_ERROR = 'ABORT_STATEMENT';

CREATE OR REPLACE TABLE CLEAN_CUSTOMERS AS
SELECT 
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    TRIM(COALESCE(CUSTOMER_NAME, 'UNKNOWN CUSTOMER')) AS CUSTOMER_NAME,
    UPPER(TRIM(CITY)) AS CITY,
    SIGNUP_DATE,
    UPPER(TRIM(CUSTOMER_TIER)) AS CUSTOMER_TIER
FROM CUSTOMERS;

CREATE OR REPLACE TABLE CLEAN_PRODUCTS AS
SELECT 
    TRIM(PRODUCT_ID) AS PRODUCT_ID,
    TRIM(PRODUCT_NAME) AS PRODUCT_NAME,
    INITCAP(TRIM(PRODUCT_CATEGORY)) AS PRODUCT_CATEGORY,
    UNIT_PRICE,
    STOCK_QUANTITY
FROM PRODUCTS;

CREATE OR REPLACE TABLE CLEAN_ORDERS AS
SELECT 
    TRIM(ORDER_ID) AS ORDER_ID,
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    TRIM(PRODUCT_ID) AS PRODUCT_ID,
    QUANTITY,
    ORDER_DATETIME,
    INITCAP(TRIM(ORDER_STATUS)) AS ORDER_STATUS,
    TRIM(PAYMENT_MODE) AS PAYMENT_MODE
FROM ORDERS;

SELECT 'CLEAN_CUSTOMERS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM CLEAN_CUSTOMERS
UNION ALL
SELECT 'CLEAN_PRODUCTS', COUNT(*) FROM CLEAN_PRODUCTS
UNION ALL
SELECT 'CLEAN_ORDERS', COUNT(*) FROM CLEAN_ORDERS;

SELECT 
    p.PRODUCT_CATEGORY,
    COUNT(o.ORDER_ID) AS ORDERS_COUNT,
    SUM(o.QUANTITY) AS TOTAL_QUANTITY_SOLD,
    SUM(o.QUANTITY * p.UNIT_PRICE) AS TOTAL_REVENUE,
    ROUND(AVG(o.QUANTITY * p.UNIT_PRICE), 2) AS AVG_ORDER_VALUE
FROM CLEAN_ORDERS o
JOIN CLEAN_PRODUCTS p ON o.PRODUCT_ID = p.PRODUCT_ID
WHERE o.ORDER_STATUS = 'Delivered'
GROUP BY p.PRODUCT_CATEGORY
ORDER BY TOTAL_REVENUE DESC;

SELECT 
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.CITY,
    c.SIGNUP_DATE,
    c.CUSTOMER_TIER
FROM CLEAN_CUSTOMERS c
LEFT JOIN CLEAN_ORDERS o ON c.CUSTOMER_ID = o.CUSTOMER_ID
WHERE o.ORDER_ID IS NULL;

SELECT 
    c.CITY,
    COUNT(o.ORDER_ID) AS ORDERS_COUNT,
    SUM(o.QUANTITY * p.UNIT_PRICE) AS REVENUE
FROM CLEAN_ORDERS o
JOIN CLEAN_CUSTOMERS c ON o.CUSTOMER_ID = c.CUSTOMER_ID
JOIN CLEAN_PRODUCTS p ON o.PRODUCT_ID = p.PRODUCT_ID
WHERE o.ORDER_STATUS = 'Delivered'
GROUP BY c.CITY
ORDER BY c.CITY ASC, REVENUE DESC;

DROP TABLE IF EXISTS CLEAN_ORDERS;
DROP TABLE IF EXISTS CLEAN_PRODUCTS;
DROP TABLE IF EXISTS CLEAN_CUSTOMERS;
DROP TABLE IF EXISTS ORDERS;
DROP TABLE IF EXISTS PRODUCTS;
DROP TABLE IF EXISTS CUSTOMERS;

DROP STAGE IF EXISTS AJI_STAGE_V2;

DROP FILE FORMAT IF EXISTS AJI_FILE_FORMAT_V2;

DROP SCHEMA IF EXISTS AJI_DB_V2.AJI_SCHEMA_V2;

DROP WAREHOUSE IF EXISTS AJI_WAREHOUSE_V2;

DROP DATABASE IF EXISTS AJI_DB_V2;