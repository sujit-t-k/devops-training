CREATE DATABASE AJI_DB_V3;

SHOW DATABASES LIKE 'AJI_DB_V3';

USE DATABASE AJI_DB_V3;

CREATE SCHEMA AJI_DB_V3.AJI_SCHEMA_V3;

SHOW SCHEMAS IN DATABASE AJI_DB_V3;

USE SCHEMA AJI_SCHEMA_V3;

CREATE TABLE ORDERS (
    ORDER_ID         VARCHAR(16),
    ORDER_TIMESTAMP  TIMESTAMP_NTZ,
    CUSTOMER_NAME    VARCHAR(64),
    CITY             VARCHAR(32),
    PRODUCT_NAME     VARCHAR(64),
    PRODUCT_CATEGORY VARCHAR(32),
    UNIT_PRICE       NUMBER(10,2),
    QUANTITY         INT,
    REVENUE          NUMBER(12,2)
);

SHOW TABLES IN SCHEMA AJI_DB_V3.AJI_SCHEMA_V3;

CREATE WAREHOUSE AJI_WH_V3;

USE WAREHOUSE AJI_WH_V3;

CREATE FILE FORMAT AJI_FILE_FORMAT_V3
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE AJI_STAGE_V3
    FILE_FORMAT = AJI_FILE_FORMAT_V3;

SHOW STAGES IN SCHEMA AJI_DB_V3.AJI_SCHEMA_V3;

SHOW FILE FORMATS IN AJI_DB_V3.AJI_SCHEMA_V3;

LIST @AJI_STAGE_V3;

COPY INTO ORDERS
FROM @AJI_STAGE_V3
FILES = ('ecommerce_orders.csv')
FILE_FORMAT = (FORMAT_NAME = 'AJI_FILE_FORMAT_V3')
ON_ERROR = 'ABORT_STATEMENT';

DESCRIBE TABLE ORDERS;

DROP DATABASE AJI_DB_V3;

DROP WAREHOUSE AJI_WH_V3;